/**
 * Reads a phone test script the platform rendered for Taqwright (generators/taqwright.ts) back into the steps it performs, so a device farm runs
 * exactly the script the test has, step by step, through the WebDriver client.
 *
 * Only the platform's own output is accepted: a closed grammar (the lines `renderStep` writes, string and template literals with the placeholders
 * `expr` writes). Anything else (a code test, a script edited by hand, a data-set script with one test per row, a one-time code) is refused with a
 * plain reason, never guessed at, and never evaluated as code.
 */
import { FIRST_OF_HELPER, taqwrightGenerator } from "../../generators/taqwright.js";
import { TestSpecSchema } from "../../spec/schema.js";

export type FarmLocator =
    | { by: "text"; value: Expr; exact: boolean }
    | { by: "label"; value: Expr }
    | { by: "testId"; value: Expr }
    | { by: "placeholder"; value: Expr; exact: boolean }
    | { by: "role"; role: string; name?: Expr }
    // Phone exploration locators (R24): an Android UiSelector or a relative XPath, a numbered match, and fallbacks tried in order (`.or`).
    | { by: "uiSelector"; value: Expr }
    | { by: "xpath"; value: Expr }
    | { by: "nth"; of: FarmLocator; n: number }
    | { by: "any"; of: FarmLocator[] };

export type FarmOp =
    | { op: "noop"; note: string }
    | { op: "deepLink"; url: Expr }
    | { op: "click"; loc: FarmLocator }
    | { op: "fill"; loc: FarmLocator; text: Expr }
    | { op: "select"; loc: FarmLocator; text: Expr }
    | { op: "check"; loc: FarmLocator; checked: boolean }
    | { op: "scrollIntoView"; loc: FarmLocator }
    | { op: "back" }
    | { op: "home" }
    | { op: "scroll"; direction: Direction; swipe: boolean }
    | { op: "key"; key: string }
    | { op: "wait"; ms: number }
    | { op: "expect"; loc: FarmLocator; check: "visible" | "hidden" | "enabled" | "disabled" }
    | { op: "expectText"; loc: FarmLocator; check: "text" | "value"; expected: Expr }
    | { op: "expectCount"; loc: FarmLocator; count: number }
    /** Answer a permission question if it shows within `waitMs`; never a failure. */
    | { op: "permission"; loc: FarmLocator; waitMs: number };

export type Direction = "up" | "down" | "left" | "right";

export interface FarmStep {
    title: string;
    op: FarmOp;
}

/** A string expression: literal pieces and the placeholders the generator writes. Evaluated only when the step runs. */
export type Expr = Array<{ lit: string } | { env: string } | { data: string } | { unique: true }>;

export interface ReadScript {
    title: string;
    /** The test's `data` object as written (evaluated per run). */
    data: Array<[string, Expr]>;
    steps: FarmStep[];
}

export const MAX_FARM_STEPS = 200;

export class ScriptReadError extends Error {}

/** Position just after the n-th line break (the end of line n, 1-based). */
function nthLineEnd(s: string, n: number): number {
    let at = -1;
    for (let i = 0; i < n; i++) {
        at = s.indexOf("\n", at + 1);
        if (at === -1) return s.length;
    }
    return at + 1;
}

let fixedParts: { header: string; beforeData: string; betweenDataAndTest: string } | undefined;
/** The generator's fixed text, taken from a script it renders now (so a change to the generator is followed, never guessed). */
function skeleton(): NonNullable<typeof fixedParts> {
    if (fixedParts) return fixedParts;
    const sample = taqwrightGenerator.render(TestSpecSchema.parse({ testId: "MOB-000", title: "Sample", kind: "mobile", category: "Sample", steps: [{ action: "press", key: "device:back" }] }), { baseUrl: "android-app://x.y" }).content;
    const data = /^const data: Record<string, string> = \{\n([\s\S]*?)\n\};$/m.exec(sample)!;
    const test = /^test\(/m.exec(sample)!;
    const headEnd = nthLineEnd(sample, 3);
    fixedParts = { header: sample.slice(sample.indexOf("\n") + 1, headEnd), beforeData: sample.slice(headEnd, data.index), betweenDataAndTest: sample.slice(data.index + data[0].length, test.index) };
    return fixedParts;
}

const NOT_OURS ="This test's script was changed by hand or is a code test. Device farms run only tests written by the platform; run it on a phone of this computer or a runner instead.";

export function readFarmScript(content: string): ReadScript {
    if (content.length > 400_000) throw new ScriptReadError("This test's script is too large to run on a device farm.");
    if (!/^\/\/ Generated by AI Testing Platform from the canonical test specification \(Taqwright \/ Appium\)\./m.test(content)) throw new ScriptReadError(NOT_OURS);
    if (/^const ROWS: Array/m.test(content)) throw new ScriptReadError("Tests that run once per row of a data set can't run on a device farm yet. Run them on a phone of this computer or a runner.");
    if (/totpCode\(/.test(content)) throw new ScriptReadError("Tests that type a one-time sign-in code can't run on a device farm yet.");
    // Phone checks (start-up time, accessibility) are measured through adb on the phone's own computer: a farm run would skip them silently, so it refuses.
    if (/^\/\/ phone-check: /m.test(content.slice(0, 2000))) throw new ScriptReadError("Phone checks (start-up time, accessibility) need the phone to be on this computer or a runner. They don't run on a device farm yet.");

    const data: Array<[string, Expr]> = [];
    const dataBlock = /^const data: Record<string, string> = \{\n([\s\S]*?)\n\};$/m.exec(content);
    if (!dataBlock) throw new ScriptReadError(NOT_OURS);
    for (const line of dataBlock[1]!.split("\n")) {
        const t = line.trim();
        if (t === "unique," || t === "") continue;
        const p = new P(t);
        const key = p.string();
        p.eat(":");
        p.ws();
        const value = p.expr();
        p.eat(",");
        p.end();
        data.push([key, value]);
    }

    const testLine = /^test\(("(?:[^"\\\n]|\\.)*"), async \(\{ mobile \}\) => \{$/m.exec(content);
    if (!testLine) throw new ScriptReadError(NOT_OURS);
    // Everything around the data and the steps (imports, beforeEach, afterEach) must be exactly what the generator writes today.
    const fixed = skeleton();
    const headEnd = nthLineEnd(content, 3);
    if (content.slice(content.indexOf("\n") + 1, headEnd) !== fixed.header || content.slice(headEnd, dataBlock.index) !== fixed.beforeData || content.slice(dataBlock.index + dataBlock[0].length, testLine.index).replace(FIRST_OF_HELPER, "") !== fixed.betweenDataAndTest) throw new ScriptReadError(NOT_OURS);
    const title = JSON.parse(testLine[1]!) as string;
    const body = content.slice(testLine.index + testLine[0].length);
    const steps: FarmStep[] = [];
    const STEP = /^ {4}await test\.step\(("(?:[^"\\\n]|\\.)*"), async \(\) => \{\n((?: {8}.*\n){1,4}) {4}\}\);$/gm;
    let m: RegExpExecArray | null;
    let consumed = 0;
    while ((m = STEP.exec(body))) {
        // Nothing but steps may sit between the test's start and its end.
        if (body.slice(consumed, m.index).trim() !== "") throw new ScriptReadError(NOT_OURS);
        consumed = m.index + m[0].length;
        const lines = m[2]!.replace(/\n$/, "").split("\n").map((l) => l.slice(8));
        steps.push({ title: JSON.parse(m[1]!) as string, op: lines.length === 1 ? readLine(lines[0]!) : readPermission(lines) });
        if (steps.length > MAX_FARM_STEPS) throw new ScriptReadError(`A test can have at most ${MAX_FARM_STEPS} steps on a device farm.`);
    }
    if (body.slice(consumed).trim() !== "});") throw new ScriptReadError(NOT_OURS);
    return { title, data, steps };
}

const DIRS = new Set(["up", "down", "left", "right"]);

/**
 * The block mobile/state/permission-step.ts renders for "Allow … when asked": wait up to its tries for the answer's button, tap it if it shows, never
 * fail. Only that exact shape is accepted.
 */
function readPermission(lines: string[]): FarmOp {
    const [note, decl, wait, tap] = lines;
    if (lines.length !== 4 || !note!.startsWith("// ") || !decl!.startsWith("const answer = ") || !decl!.endsWith(";")) throw new ScriptReadError(NOT_OURS);
    const w = /^for \(let i = 0; i < (\d{1,2}) && !\(await answer\.isVisible\(\)\.catch\(\(\) => false\)\); i\+\+\) await mobile\.waitForTimeout\(500\);$/.exec(wait!);
    if (!w || tap !== "if (await answer.isVisible().catch(() => false)) await answer.click().catch(() => undefined);") throw new ScriptReadError(NOT_OURS);
    const p = new P(decl!.slice("const answer = ".length, -1));
    const loc = p.locator();
    p.end();
    return { op: "permission", loc, waitMs: Number(w[1]) * 500 };
}

/** One rendered step line → what it does. */
export function readLine(line: string): FarmOp {
    if (line.startsWith("// ")) return { op: "noop", note: line.slice(3) };
    const p = new P(line);
    p.eat("await ");
    if (p.peek("expect(")) {
        p.eat("expect(");
        const loc = p.locator();
        p.eat(").");
        const method = p.ident();
        p.eat("(");
        let out: FarmOp;
        switch (method) {
            case "toBeVisible":
            case "toBeHidden":
            case "toBeEnabled":
            case "toBeDisabled":
                out = { op: "expect", loc, check: method.slice(4).toLowerCase() as "visible" | "hidden" | "enabled" | "disabled" };
                break;
            case "toContainText":
            case "toHaveValue":
                out = { op: "expectText", loc, check: method === "toContainText" ? "text" : "value", expected: p.expr() };
                break;
            case "toHaveCount":
                out = { op: "expectCount", loc, count: p.number() };
                break;
            default:
                throw new ScriptReadError(NOT_OURS);
        }
        p.eat(");");
        p.end();
        return out;
    }
    const save = p.pos;
    // A step on an element with fallbacks starts with the generator's helper: `(await firstOf(...)).click()`.
    const chained = p.peek("(await firstOf(");
    if (!chained) p.eat("mobile.");
    const name = chained ? "getBy" : p.ident();
    if (name.startsWith("getBy")) {
        p.pos = save;
        const loc = p.locator();
        p.eat(".");
        const action = p.ident();
        p.eat("(");
        let out: FarmOp;
        switch (action) {
            case "click":
                out = { op: "click", loc };
                break;
            case "fill":
                out = { op: "fill", loc, text: p.expr() };
                break;
            case "selectOption":
                out = { op: "select", loc, text: p.expr() };
                break;
            case "check":
            case "uncheck":
                out = { op: "check", loc, checked: action === "check" };
                break;
            case "scrollIntoView":
                out = { op: "scrollIntoView", loc };
                break;
            default:
                throw new ScriptReadError(NOT_OURS);
        }
        p.eat(");");
        p.end();
        return out;
    }
    p.eat("(");
    let out: FarmOp;
    switch (name) {
        case "goBack":
            out = { op: "back" };
            break;
        case "pressButton": {
            if (p.string() !== "HOME") throw new ScriptReadError(NOT_OURS);
            out = { op: "home" };
            break;
        }
        case "scroll":
        case "swipe": {
            const d = p.string();
            if (!DIRS.has(d)) throw new ScriptReadError(NOT_OURS);
            out = { op: "scroll", direction: d as Direction, swipe: name === "swipe" };
            break;
        }
        case "press":
            out = { op: "key", key: p.string() };
            break;
        case "waitForTimeout":
            out = { op: "wait", ms: p.number() };
            break;
        case "openDeepLink":
            out = { op: "deepLink", url: p.expr() };
            break;
        default:
            throw new ScriptReadError(NOT_OURS);
    }
    p.eat(");");
    p.end();
    return out;
}

/** A tiny reader over one line of generated code: string and template literals, numbers, identifiers. Never evaluates anything. */
class P {
    pos = 0;
    constructor(private readonly s: string) {}
    peek(t: string): boolean {
        return this.s.startsWith(t, this.pos);
    }
    eat(t: string): void {
        if (!this.peek(t)) throw new ScriptReadError(NOT_OURS);
        this.pos += t.length;
    }
    ws(): void {
        while (this.s[this.pos] === " ") this.pos++;
    }
    end(): void {
        if (this.pos !== this.s.length) throw new ScriptReadError(NOT_OURS);
    }
    ident(): string {
        const m = /^[A-Za-z_][A-Za-z0-9_]*/.exec(this.s.slice(this.pos));
        if (!m) throw new ScriptReadError(NOT_OURS);
        this.pos += m[0].length;
        return m[0];
    }
    number(): number {
        const m = /^[0-9]{1,9}/.exec(this.s.slice(this.pos));
        if (!m) throw new ScriptReadError(NOT_OURS);
        this.pos += m[0].length;
        return Number(m[0]);
    }
    /** A JSON string literal (what `lit` writes). */
    string(): string {
        const m = /^"(?:[^"\\]|\\.)*"/.exec(this.s.slice(this.pos));
        if (!m) throw new ScriptReadError(NOT_OURS);
        this.pos += m[0].length;
        try {
            return JSON.parse(m[0]) as string;
        } catch {
            throw new ScriptReadError(NOT_OURS);
        }
    }
    /** What `expr` writes: a string literal, or a template literal whose placeholders are the generator's own. */
    expr(): Expr {
        if (this.peek('"')) return [{ lit: this.string() }];
        this.eat("`");
        const out: Expr = [];
        let lit = "";
        while (this.pos < this.s.length) {
            const c = this.s[this.pos]!;
            if (c === "`") {
                this.pos++;
                if (lit) out.push({ lit });
                return out;
            }
            if (c === "\\") {
                const n = this.s[this.pos + 1];
                if (n === "\\" || n === "`") {
                    lit += n;
                    this.pos += 2;
                    continue;
                }
                if (n === "$" && this.s[this.pos + 2] === "{") {
                    lit += "${";
                    this.pos += 3;
                    continue;
                }
                throw new ScriptReadError(NOT_OURS);
            }
            if (c === "$" && this.s[this.pos + 1] === "{") {
                if (lit) out.push({ lit });
                lit = "";
                this.pos += 2;
                out.push(this.placeholder());
                this.eat("}");
                continue;
            }
            lit += c;
            this.pos++;
        }
        throw new ScriptReadError(NOT_OURS);
    }
    private placeholder(): Expr[number] {
        if (this.peek("unique}")) {
            this.pos += "unique".length;
            return { unique: true };
        }
        const env = /^\(process\.env\.([A-Z][A-Z0-9_]{0,80}) \?\? ""\)/.exec(this.s.slice(this.pos));
        if (env) {
            this.pos += env[0].length;
            return { env: env[1]! };
        }
        if (this.peek("data[")) {
            this.eat("data[");
            const key = this.string();
            this.eat('] ?? ""');
            return { data: key };
        }
        if (this.peek('""')) {
            this.pos += 2;
            return { lit: "" };
        }
        throw new ScriptReadError(NOT_OURS);
    }
    /** `mobile.getByX(...)` as the generator writes it, with its number (`.nth(n)`) and its fallbacks (`.or(mobile.getByY(...))`, at most 3). */
    locator(): FarmLocator {
        // `(await firstOf(ms, main, fallback...))`: the first that finds the element (the generator's helper, R24).
        if (this.peek("(await firstOf(")) {
            this.eat("(await firstOf(");
            this.number();
            const any: FarmLocator[] = [];
            while (this.peek(", ")) {
                if (any.length > 3) throw new ScriptReadError(NOT_OURS);
                this.eat(", ");
                any.push(this.numbered(this.single()));
            }
            this.eat("))");
            if (any.length < 2) throw new ScriptReadError(NOT_OURS);
            return { by: "any", of: any };
        }
        return this.numbered(this.single());
    }
    private numbered(l: FarmLocator): FarmLocator {
        if (!this.peek(".nth(")) return l;
        this.eat(".nth(");
        const n = this.number();
        this.eat(")");
        return { by: "nth", of: l, n };
    }
    private single(): FarmLocator {
        this.eat("mobile.");
        const fn = this.ident();
        this.eat("(");
        let out: FarmLocator;
        switch (fn) {
            case "getByText":
                out = { by: "text", value: this.expr(), exact: true };
                break;
            case "getByLabel":
                out = { by: "label", value: this.expr() };
                break;
            case "getByTestId":
                out = { by: "testId", value: this.expr() };
                break;
            case "getByPlaceholder":
                out = { by: "placeholder", value: this.expr(), exact: true };
                break;
            case "getByRole": {
                const role = this.string();
                if (this.peek(", { name: ")) {
                    this.eat(", { name: ");
                    const name = this.expr();
                    this.eat(" }");
                    out = { by: "role", role, name };
                } else out = { by: "role", role };
                break;
            }
            case "getByUiSelector":
                out = { by: "uiSelector", value: this.expr() };
                break;
            case "getByXpath":
                out = { by: "xpath", value: this.expr() };
                break;
            case "getByCss":
                throw new ScriptReadError("This test finds an element by a CSS selector, which Android apps don't have. Change the step to use a name, a label or an id.");
            default:
                throw new ScriptReadError(NOT_OURS);
        }
        this.eat(")");
        return out;
    }
}

/** The value of an expression for one run. `vars` holds the run's environment (the test account); anything else is empty, as in a Taqwright run. */
export function evaluate(e: Expr, ctx: { vars: Record<string, string>; data: Record<string, string>; unique: string }): string {
    return e.map((part) => ("lit" in part ? part.lit : "env" in part ? (ctx.vars[part.env] ?? "") : "data" in part ? (ctx.data[part.data] ?? "") : ctx.unique)).join("");
}

/** The `data` object of a script for one run (initialisers cannot read `data` itself, as in the script). */
export function evaluateData(read: ReadScript, vars: Record<string, string>, unique: string): Record<string, string> {
    const data: Record<string, string> = { unique };
    for (const [k, v] of read.data) data[k] = evaluate(v, { vars, data: {}, unique });
    return data;
}
